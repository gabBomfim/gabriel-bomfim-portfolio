export function translate(text: string, locale: Locale) {
  return locale === "pt-BR" ? (pt[text] ?? text) : text;
}

export function localize<T>(value: T, locale: Locale): T {
  if (typeof value === "string") return translate(value, locale) as T;
  if (Array.isArray(value))
    return value.map((item) => localize(item, locale)) as T;
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, localize(item, locale)]),
    ) as T;
  return value;
}
